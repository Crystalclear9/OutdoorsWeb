"""Build self-hosted, demand-loaded Source Han Sans CN variable-font subsets.
Requires fonttools and brotli. Input: official 2.005R CN variable WOFF2.
Source: https://github.com/adobe-fonts/source-han-sans/tree/release/Variable/WOFF2/TTF/Subset
Usage: python scripts/prepare-ui-font.py /path/to/SourceHanSansCN-VF.ttf.woff2
Keep LICENSE.txt with the generated fonts. No glyph outlines are changed.
"""
from pathlib import Path
from collections import defaultdict
import sys
import io
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.ttLib import woff2
# Use moderate Brotli compression to keep deterministic rebuilds practical.
_brotli_compress = woff2.brotli.compress
woff2.brotli.compress = lambda data, **kwargs: _brotli_compress(data, quality=5, **kwargs)

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
output = root / 'src/assets/fonts/source-han'
output.mkdir(parents=True, exist_ok=True)
# Decode WOFF2 once; repeated glyph reconstruction dominates subset build time.
with TTFont(source) as font:
    supported = set(font.getBestCmap())
    font.flavor = None
    decoded = io.BytesIO()
    font.save(decoded)
font_bytes = decoded.getvalue()
# UI glyphs load together. Remaining glyphs retain full source coverage and are
# fetched only when user content uses them; never subset solely to static labels.
ui = set(range(32, 127))
for file in (root / 'src').glob('*.jsx'):
    ui.update(map(ord, file.read_text()))
for file in (root / 'src').glob('*.js'):
    ui.update(map(ord, file.read_text()))
ui &= supported
parts = defaultdict(set)
for cp in supported - ui:
    parts[f'extra-{cp // 1024:03x}'].add(cp)
parts['ui'] = ui

def ranges(points):
    result = []
    for cp in sorted(points):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in result)

css = ['/* Generated by scripts/prepare-ui-font.py; Source Han Sans 2.005R, SIL OFL. */']
for name, points in sorted(parts.items()):
    font = TTFont(io.BytesIO(font_bytes))
    # Subsetting is a modification under OFL; avoid the reserved name "Source".
    names = {1: "Campus Sans", 3: "CampusSans-2.005R-subset", 4: "Campus Sans", 6: "CampusSans", 16: "Campus Sans", 25: "CampusSans"}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_legacy = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    font.flavor = 'woff2'
    font.save(output / f'{name}.woff2')
    font.close()
    css.append(f'''@font-face {{
  font-family: "Campus Sans";
  src: url("./assets/fonts/source-han/{name}.woff2") format("woff2");
  font-weight: 250 900;
  font-style: normal;
  font-display: swap;
  unicode-range: {ranges(points)};
}}''')
(root / 'src/fonts.css').write_text('\n'.join(css) + '\n')
print(f'Generated {len(parts)} subsets covering {len(supported)} codepoints')
